"""Generate expression overloads from the bindings and reflected object ancestry.

Run after tvm-ffi-stubgen with the same compiler library. Object blocks and local
type maps provide the declarations. Blocks remain owned by stubgen; this file adds
only invocations of def_ex_op_overloads!.
"""

from __future__ import annotations

import argparse
import ctypes
import re
from pathlib import Path

from tvm_ffi.stub.lib_state import object_info_from_type_key

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src"
OUTPUT = SOURCE / "ir/prim/expr_ops_generated.rs"
TYPE_MAP = re.compile(
    r"^// tvm-ffi-stubgen\(ty-map\): (\S+)\s*->\s*(crate::[\w:]+)\s*$", re.MULTILINE
)
OBJECT_BLOCK = re.compile(r"^// tvm-ffi-stubgen\(begin\): object/(\S+)\s*$", re.MULTILINE)


def expression_wrappers(source: Path) -> list[str]:
    """Resolve every declared Expr descendant, including abstract and opaque handles."""
    declarations: dict[str, str] = {}
    for path in sorted(source.rglob("*.rs")):
        module = list(path.relative_to(source).with_suffix("").parts)
        if module[-1] in ("lib", "mod"):
            module.pop()
        # Rust's type module is spelled r#type in generated paths.
        module = ["r#type" if part == "type" else part for part in module]
        text = path.read_text()
        for key in OBJECT_BLOCK.findall(text):
            if key in declarations:
                raise ValueError(f"Duplicate object block: {key}")
            declarations[key] = "::".join(("crate", *module, key.rsplit(".", 1)[-1]))
        for key, name in TYPE_MAP.findall(text):
            if key in declarations and declarations[key] != name:
                raise ValueError(f"Conflicting object declaration: {key}")
            declarations[key] = name
    if "ir.Expr" not in declarations:
        raise ValueError("Missing object block for ir.Expr")
    return [
        declarations[key]
        for key in sorted(declarations)
        if key == "ir.Expr" or "ir.Expr" in object_info_from_type_key(key).ancestors
    ]


def render(source: Path) -> str:
    """Produce stable Rust source without changing wrapper layouts or upcasts."""
    license_text = (source / "ir/prim/expr_ops.rs").read_text().split("//!", 1)[0]
    return (
        license_text
        + "// Generated by rust/scripts/generate_expr_ops.py. Do not edit.\n\n"
        + "".join(f"crate::def_ex_op_overloads!({name});\n" for name in expression_wrappers(source))
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dll", required=True, help="Compiler library used by tvm-ffi-stubgen")
    parser.add_argument(
        "--check", action="store_true", help="Fail if generated overloads are stale"
    )
    args = parser.parse_args()
    library = ctypes.CDLL(args.dll)
    generated = render(SOURCE)
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != generated:
            parser.exit(
                1, "Expression overloads are stale; rerun rust/scripts/generate_expr_ops.py\n"
            )
    else:
        OUTPUT.write_text(generated)
    # Keep the library handle alive until all reflection calls have finished.
    del library
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
